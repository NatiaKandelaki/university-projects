/*
 * main.c
 * Lie Detector — PPG + GSR + Temperature
 * ATmega168 @ 8MHz  —  50 Hz sampling
 * Author: Natia
 *
 * Packet format (sent every BUF_SIZE samples):
 *   [0xAA] [PPG_H] [PPG_L] [GSR_H] [GSR_L] [TEMP_H] [TEMP_L]
 *
 * Pin mapping:
 *   PC0 (ADC0) — PPG
 *   PC1 (ADC1) — GSR
 *   PD2        — DS18B20 (1-Wire)
 */

#define F_CPU 8000000UL
#include <avr/io.h>
#include <avr/interrupt.h>
#include <util/delay.h>

/* ??? Buffer ??????????????????????????????????????????? */
#define BUF_SIZE 100u

static volatile uint16_t ppg_buf1[BUF_SIZE];
static volatile uint16_t ppg_buf2[BUF_SIZE];
static volatile uint16_t gsr_buf1[BUF_SIZE];
static volatile uint16_t gsr_buf2[BUF_SIZE];

/* ??? ADC state ???????????????????????????????????????? */
static volatile uint8_t  adc_active  = 0;   /* which ping-pong buffer fills now */
static volatile uint16_t adc_idx     = 0;   /* sample index inside buffer       */
static volatile uint8_t  adc_channel = 0;   /* 0 = PPG, 1 = GSR                 */

/* ??? TX state ????????????????????????????????????????? */
static volatile uint8_t  tx_busy   = 0;
static volatile uint8_t  tx_active = 0;
static volatile uint16_t tx_idx    = 0;
/*
 * tx_phase:
 *  0 = send 0xAA header
 *  1 = PPG high byte
 *  2 = PPG low  byte
 *  3 = GSR high byte
 *  4 = GSR low  byte
 *  5 = TEMP high byte
 *  6 = TEMP low  byte  ? then advance tx_idx
 */
static volatile uint8_t  tx_phase  = 0;

/* ??? Temperature (updated once per packet) ???????????? */
static volatile int16_t  last_temp_raw = 0;  /* DS18B20 raw 16-bit value */

/* ???????????????????????????????????????????????????????
 *  DS18B20  —  1-Wire  (bit-bang on PD2)
 * ??????????????????????????????????????????????????????? */
#define OW_DDR   DDRD
#define OW_PORT  PORTD
#define OW_PIN   PIND
#define OW_BIT   PD2

static inline void ow_low(void)  { OW_DDR  |=  (1 << OW_BIT); OW_PORT &= ~(1 << OW_BIT); }
static inline void ow_release(void) { OW_DDR &= ~(1 << OW_BIT); OW_PORT |=  (1 << OW_BIT); }
static inline uint8_t ow_read_bit(void) { return (OW_PIN >> OW_BIT) & 1; }

/* Returns 1 if device present, 0 if not */
static uint8_t ow_reset(void)
{
    ow_low();
    _delay_us(480);
    ow_release();
    _delay_us(70);
    uint8_t presence = !ow_read_bit();
    _delay_us(410);
    return presence;
}

static void ow_write_bit(uint8_t bit)
{
    ow_low();
    if (bit) { _delay_us(6); ow_release(); _delay_us(64); }
    else      { _delay_us(60); ow_release(); _delay_us(10); }
}

static uint8_t ow_read_bit_val(void)
{
    ow_low();
    _delay_us(6);
    ow_release();
    _delay_us(9);
    uint8_t val = ow_read_bit();
    _delay_us(55);
    return val;
}

static void ow_write_byte(uint8_t byte)
{
    for (uint8_t i = 0; i < 8; i++) { ow_write_bit(byte & 1); byte >>= 1; }
}

static uint8_t ow_read_byte(void)
{
    uint8_t val = 0;
    for (uint8_t i = 0; i < 8; i++) { if (ow_read_bit_val()) val |= (1 << i); }
    return val;
}

/*
 * Start a conversion (non-blocking).
 * Call ow_read_temp() at least 750 ms later.
 */
static void ow_start_conversion(void)
{
    ow_reset();
    ow_write_byte(0xCC); /* SKIP ROM  */
    ow_write_byte(0x44); /* CONVERT T */
}

/* Read scratchpad and return raw 16-bit value */
static int16_t ow_read_temp(void)
{
    ow_reset();
    ow_write_byte(0xCC); /* SKIP ROM      */
    ow_write_byte(0xBE); /* READ SCRATCH  */
    uint8_t lo = ow_read_byte();
    uint8_t hi = ow_read_byte();
    return (int16_t)((uint16_t)hi << 8 | lo);
}

/* ???????????????????????????????????????????????????????
 *  Helper: buffer pointers
 * ??????????????????????????????????????????????????????? */
static inline volatile uint16_t* ppg_buf(uint8_t which)
{ return (which == 0) ? ppg_buf1 : ppg_buf2; }

static inline volatile uint16_t* gsr_buf(uint8_t which)
{ return (which == 0) ? gsr_buf1 : gsr_buf2; }

/* ???????????????????????????????????????????????????????
 *  TIMER0 — fires at 50 Hz, triggers ADC
 * ??????????????????????????????????????????????????????? */
ISR(TIMER0_COMPA_vect)
{
    /* Start PPG (ADC0) first */
    ADMUX  = (1 << REFS0) | 0x00;   /* AVcc ref, channel 0 */
    ADCSRA |= (1 << ADSC);
    adc_channel = 0;
}

/* ???????????????????????????????????????????????????????
 *  ADC — alternates between PPG and GSR each timer tick
 * ??????????????????????????????????????????????????????? */
ISR(ADC_vect)
{
    uint16_t result = ADC;

    if (adc_channel == 0)
    {
        /* Store PPG, then immediately sample GSR */
        ppg_buf(adc_active)[adc_idx] = result;
        ADMUX  = (1 << REFS0) | 0x01;   /* channel 1 = GSR */
        ADCSRA |= (1 << ADSC);
        adc_channel = 1;
    }
    else
    {
        /* Store GSR, advance index */
        gsr_buf(adc_active)[adc_idx] = result;
        adc_idx++;

        if (adc_idx >= BUF_SIZE)
        {
            adc_idx = 0;
            if (!tx_busy)
            {
                tx_active = adc_active;
                adc_active ^= 1;
                tx_idx   = 0;
                tx_phase = 0;
                tx_busy  = 1;
                UDR0 = 0xAA;   /* send sync byte to kick off TX ISR */
            }
        }
    }
}

/* ???????????????????????????????????????????????????????
 *  USART TX — sends one 7-byte packet per sample:
 *  [0xAA] [PPG_H] [PPG_L] [GSR_H] [GSR_L] [TEMP_H] [TEMP_L]
 * ??????????????????????????????????????????????????????? */
ISR(USART_TX_vect)
{
    if (!tx_busy) return;

    volatile uint16_t *pb = ppg_buf(tx_active);
    volatile uint16_t *gb = gsr_buf(tx_active);

    switch (tx_phase)
    {
        case 0:   /* PPG high */
            UDR0 = (uint8_t)(pb[tx_idx] >> 8);
            tx_phase = 1;
            break;

        case 1:   /* PPG low */
            UDR0 = (uint8_t)(pb[tx_idx] & 0xFF);
            tx_phase = 2;
            break;

        case 2:   /* GSR high */
            UDR0 = (uint8_t)(gb[tx_idx] >> 8);
            tx_phase = 3;
            break;

        case 3:   /* GSR low */
            UDR0 = (uint8_t)(gb[tx_idx] & 0xFF);
            tx_phase = 4;
            break;

        case 4:   /* TEMP high */
            UDR0 = (uint8_t)((uint16_t)last_temp_raw >> 8);
            tx_phase = 5;
            break;

        case 5:   /* TEMP low — then move to next sample */
            UDR0 = (uint8_t)((uint16_t)last_temp_raw & 0xFF);
            tx_phase = 0;
            pb[tx_idx] = 0;
            gb[tx_idx] = 0;
            tx_idx++;
            if (tx_idx >= BUF_SIZE)
            {
                tx_busy = 0;   /* packet done */
            }
            else
            {
                /* next sample starts with sync byte */
                UDR0 = 0xAA;
            }
            break;
    }
}

/* ???????????????????????????????????????????????????????
 *  Peripheral init
 * ??????????????????????????????????????????????????????? */
static void uart_init(void)
{
    UBRR0H = 0x00;
    UBRR0L = 0x33;                            /* 9600 baud @ 8MHz */
    UCSR0C = 0x06;                            /* 8N1              */
    UCSR0A = 0x00;
    UCSR0B = (1 << TXCIE0) | (1 << TXEN0);   /* TX + TX-complete IRQ */
}

static void adc_init(void)
{
    ADCSRA = (1 << ADEN) | (1 << ADIE)
           | (1 << ADPS2) | (1 << ADPS1);    /* prescaler /64 */
    ADMUX  = (1 << REFS0);                    /* AVcc ref, ch0  */
    DIDR0  = (1 << ADC0D) | (1 << ADC1D);    /* disable digital buffers */
}

static void timer_init(void)
{
    TCCR0A = (1 << WGM01);                   /* CTC mode       */
    TCCR0B = (1 << CS02);                    /* prescaler /256 */
    OCR0A  = 155;                            /* 8M/256/156 ? 50Hz */
    TCNT0  = 0;
    TIMSK0 = (1 << OCIE0A);
}

/* ???????????????????????????????????????????????????????
 *  Main
 * ??????????????????????????????????????????????????????? */
int main(void)
{
    /* PC0, PC1 — inputs (ADC) */
    DDRC  = 0x00;
    PORTC = 0x00;

    /* PD2 — 1-Wire (direction managed by ow_ functions) */
    ow_release();

    timer_init();
    uart_init();
    adc_init();

    /* First DS18B20 conversion (result ready after ~750 ms) */
    ow_start_conversion();

    sei();

    uint8_t prev_tx_busy = 0;

    while (1)
    {
        /*
         * Read temperature once per transmitted packet.
         * We detect the falling edge of tx_busy (packet just finished)
         * and immediately start a new conversion so the next packet
         * gets a fresh reading.
         */
        uint8_t cur = tx_busy;
        if (prev_tx_busy && !cur)
        {
            /* packet just finished ? read result of previous conversion */
            last_temp_raw = ow_read_temp();
            /* start next conversion right away */
            ow_start_conversion();
        }
        prev_tx_busy = cur;
    }
}

